- ক্রেডিট কার্ডের চুক্তিতে সুদের শর্ত থাকায় অনেক আলেম এটি ব্যবহার থেকে বিরত থাকতে বলেন; কেউ কেউ নিশ্চিতভাবে সময়মতো পুরো বিল পরিশোধের শর্তে প্রয়োজনে অনুমতি দেন। নিরাপদ পথ হলো **ডেবিট কার্ড** বা ইসলামী ব্যাংকের শরীয়াহসম্মত কার্ড ব্যবহার করা।
- কিস্তিতে কেনার ক্ষেত্রে মোট মূল্য শুরুতেই নির্ধারিত থাকলে এবং দেরিতে পরিশোধের জন্য বাড়তি টাকা আরোপ না হলে, বিক্রেতার কাছ থেকে কিস্তিতে কেনা জায়েয।

