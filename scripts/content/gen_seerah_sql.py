"""Generates supabase/content/04_seerah_biography.sql from seerah.py."""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from seerah import SEERAH, BIOGRAPHIES

ADMIN = "aa0f5ee1-177f-4374-a94e-dd78ef49c2fc"
def dq(s, tag="zq"):
    assert f"${tag}$" not in s
    return f"${tag}${s}${tag}$"
def minutes(body):
    return max(1, round(len(re.sub(r"[#>*_`!\[\]()-]", " ", body).split()) / 180))

out = ["-- Editorial Seerah chapters and biographies (generated by scripts/content/gen_seerah_sql.py).",
"""insert into public.article_categories (slug, name_bn, description_bn, sort_order) values
  ('seerah', 'সীরাত', 'রাসূলুল্লাহ ﷺ-এর জীবনী — জন্ম থেকে ইন্তেকাল পর্যন্ত ধারাবাহিক অধ্যায়', 20),
  ('biography', 'জীবনী', 'সাহাবী, তাবেয়ী ও মুসলিম মনীষীদের সংক্ষিপ্ত জীবনী', 21)
on conflict (slug) do update set name_bn = excluded.name_bn, description_bn = excluded.description_bn;"""]
for cat, items in (("seerah", SEERAH), ("biography", BIOGRAPHIES)):
    n = len(items)
    for i, a in enumerate(items):
        # Older first: chapter 1 gets the earliest timestamp so lists can sort chronologically.
        offset = (n - i) * 5 + (200 if cat == "seerah" else 100)
        out.append(f"""insert into public.articles (slug, title, excerpt, body, category_id, author_id, author_name, reading_minutes, status, published_at)
values ({dq(a['slug'])}, {dq(a['title'])}, {dq(a['excerpt'])}, {dq(a['body'])},
  (select id from public.article_categories where slug = '{cat}'), '{ADMIN}', 'যাদুল মুসলিম সম্পাদকীয় বিভাগ', {minutes(a['body'])},
  'published', now() - interval '{offset} minutes')
on conflict (slug) do update set title = excluded.title, excerpt = excluded.excerpt, body = excluded.body,
  category_id = excluded.category_id, reading_minutes = excluded.reading_minutes, status = 'published';""")
path = os.path.join(os.path.dirname(__file__), "../../supabase/content/04_seerah_biography.sql")
open(path, "w").write("\n\n".join(out) + "\n")
print("wrote", path, sum(len(x) for x in out))
